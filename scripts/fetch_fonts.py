#!/usr/bin/env python
"""Fetch the fleet's fonts from their upstream releases into fonts/.

A one-time tool, not a build step: the files it writes are committed, so a
build never touches the network for a font. Re-run it to move to a newer
upstream release (bump the version constants below) and commit the diff.

What it writes:
  - fonts/<Family>-<Weight>.woff2 and .ttf for every weight the sites use:
    woff2 for the web, ttf for the PDF tools (rsslide, rspandoc).
  - fonts/OFL-<Family>.txt, each family's licence (SIL Open Font License,
    which permits redistribution with the licence text alongside).
  - fonts/SOURCES.md, the provenance: upstream, release, URL and SHA-256 of
    every file, so what is committed can be checked against what was fetched.
  - fonts.css, the @font-face declarations for the woff2 files, generated so
    the CSS and the files cannot drift apart.

Usage:
    scripts/fetch_fonts.py            # fetch, write, report
"""

from __future__ import annotations

import hashlib
import io
import sys
import tempfile
import urllib.request
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FONTS_DIR = ROOT / "fonts"
CSS_PATH = ROOT / "fonts.css"

# ── upstream releases ────────────────────────────────────────────────────────
# Outfit ships its files in the repo tree; JetBrains Mono as a release zip.
OUTFIT_VERSION = "1.1"
OUTFIT_RAW = f"https://raw.githubusercontent.com/Outfitio/Outfit-Fonts/{OUTFIT_VERSION}"
JBM_VERSION = "2.304"
JBM_ZIP = (
    "https://github.com/JetBrains/JetBrainsMono/releases/download/"
    f"v{JBM_VERSION}/JetBrainsMono-{JBM_VERSION}.zip"
)

# The weights the sites use: themes.yaml names the families, base.css used to
# import exactly these weights from Google Fonts.
OUTFIT_WEIGHTS = [("Light", 300), ("Regular", 400), ("Medium", 500), ("SemiBold", 600), ("Bold", 700)]
JBM_WEIGHTS = [("Regular", 400), ("SemiBold", 600)]

CSS_HEADER = """\
/*
 * shared-themes/fonts.css
 *
 * GENERATED BY scripts/fetch_fonts.py — do not edit by hand.
 *
 * The @font-face declarations for the fonts in fonts/, which the design
 * tokens name (--font-sans: Outfit, --font-mono: JetBrains Mono). Link this
 * next to themes.css and publish fonts/ beside it: the URLs are relative to
 * this file. Nothing is fetched from a third party at page view.
 */
"""


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=60) as resp:
        return resp.read()


def main() -> int:
    FONTS_DIR.mkdir(exist_ok=True)
    # (family, style, weight, filename, upstream URL, bytes)
    files: list[tuple[str, str, int, str, str, bytes]] = []

    for style, weight in OUTFIT_WEIGHTS:
        for ext, sub in (("woff2", "webfonts"), ("ttf", "ttf")):
            url = f"{OUTFIT_RAW}/fonts/{sub}/Outfit-{style}.{ext}"
            files.append(("Outfit", style, weight, f"Outfit-{style}.{ext}", url, fetch(url)))
    ofl_url = f"{OUTFIT_RAW}/OFL.txt"
    licences = [("Outfit", ofl_url, fetch(ofl_url))]

    with tempfile.TemporaryDirectory() as tmp:
        zip_path = Path(tmp) / "jbm.zip"
        zip_path.write_bytes(fetch(JBM_ZIP))
        with zipfile.ZipFile(zip_path) as zf:
            for style, weight in JBM_WEIGHTS:
                for ext, sub in (("woff2", "webfonts"), ("ttf", "ttf")):
                    member = f"fonts/{sub}/JetBrainsMono-{style}.{ext}"
                    files.append((
                        "JetBrains Mono",
                        style,
                        weight,
                        f"JetBrainsMono-{style}.{ext}",
                        f"{JBM_ZIP}!{member}",
                        zf.read(member),
                    ))
            licences.append(("JetBrains Mono", f"{JBM_ZIP}!OFL.txt", zf.read("OFL.txt")))

    for _, _, _, name, _, data in files:
        (FONTS_DIR / name).write_bytes(data)
    for family, _, data in licences:
        (FONTS_DIR / f"OFL-{family.replace(' ', '')}.txt").write_bytes(data)

    sources = io.StringIO()
    sources.write("# Font sources\n\n")
    sources.write("Generated by `scripts/fetch_fonts.py`; do not edit by hand.\n\n")
    sources.write(f"- Outfit {OUTFIT_VERSION}, <https://github.com/Outfitio/Outfit-Fonts>, SIL OFL 1.1\n")
    sources.write(f"- JetBrains Mono {JBM_VERSION}, <https://github.com/JetBrains/JetBrainsMono>, SIL OFL 1.1\n\n")
    sources.write("| File | Upstream | SHA-256 |\n|---|---|---|\n")
    for _, _, _, name, url, data in files:
        sources.write(f"| `{name}` | <{url}> | `{sha256(data)}` |\n")
    for family, url, data in licences:
        sources.write(f"| `OFL-{family.replace(' ', '')}.txt` | <{url}> | `{sha256(data)}` |\n")
    (FONTS_DIR / "SOURCES.md").write_text(sources.getvalue())

    css = [CSS_HEADER]
    for family, _, weight, name, _, _ in files:
        if not name.endswith(".woff2"):
            continue
        css.append(
            "@font-face {\n"
            f'  font-family: "{family}";\n'
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f'  src: url("fonts/{name}") format("woff2");\n'
            "}"
        )
    CSS_PATH.write_text("\n\n".join(css) + "\n")

    total = sum(len(d) for *_, d in files)
    print(f"wrote {len(files)} font files ({total // 1024} KiB) to fonts/, fonts.css, fonts/SOURCES.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
